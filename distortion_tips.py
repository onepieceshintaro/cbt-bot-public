def get_tip(name: str) -> dict | None:
    """歪み名で1件取得。サブタイプ未登録なら親カテゴリにフォールバック。"""
    if name in DISTORTION_TIPS:
        return DISTORTION_TIPS[name]
    # サブタイプ → 親カテゴリのフォールバック
    if name.startswith("結論の飛躍"):
        return DISTORTION_TIPS.get("結論の飛躍")
    return None


def get_tips_for(names: list[str]) -> list[tuple[str, dict]]:
    """複数名でまとめて取得。フォールバックも適用。"""
    out = []
    for n in names:
        tip = get_tip(n)
        if tip is not None:
            out.append((n, tip))
    return out
